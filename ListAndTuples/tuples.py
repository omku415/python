#A built-in data types that let us to create immutable(cannot be changed) sequence of values.
#list is written in big bracket while tuples is written in small sprated by comma.
tup=(0,1,2)

#if we are writing single value in tuple we have to add comma in last 
tup=(1,) #this is tuple

tup(1)# this is integer

#Tuple methods

tup.index(1) # return the index of  first occurence of the 1

tup.count(1) # return the occurence of 1 in the tuples.


